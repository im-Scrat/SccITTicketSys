/* ------------------------------------------------------------- cascades */

it('takes items and attachments with the request when it is deleted', function (): void {
    $requestId = DB::table('work_support_requests')->insertGetId(wsrRow());

    DB::table('work_support_request_items')->insert([
        'work_support_request_id' => $requestId,
        'description' => 'RAM module',
        'quantity' => 1,
        'created_at' => now(),
        'updated_at' => now(),
    ]);

    DB::table('work_support_request_attachments')->insert([
        'work_support_request_id' => $requestId,
        'kind' => 'image',
        'storage_path' => 'work-support/x/photo.jpg',
        'original_filename' => 'photo.jpg',
        'created_at' => now(),
        'updated_at' => now(),
    ]);

    DB::table('work_support_requests')->where('id', $requestId)->delete();

    expect(DB::table('work_support_request_items')->where('work_support_request_id', $requestId)->count())->toBe(0)
        ->and(DB::table('work_support_request_attachments')->where('work_support_request_id', $requestId)->count())->toBe(0);
});

it('does not touch the procurement request vocabulary', function (): void {
    // OI-09: `procurement_requests` shall be neither overloaded nor redesigned.
    // The bridge is one nullable column on *our* table, pointing outwards.
    expect(Schema::hasColumn('work_support_requests', 'procurement_request_id'))->toBeTrue()
        ->and(Schema::hasColumn('procurement_requests', 'pc_unit_id'))->toBeFalse()
        ->and(Schema::hasColumn('procurement_requests', 'ticket_id'))->toBeFalse()
        ->and(Schema::hasColumn('procurement_requests', 'maintenance_record_id'))->toBeFalse();

    $check = DB::selectOne(<<<'SQL'
        SELECT pg_get_constraintdef(oid) AS def
        FROM pg_constraint
        WHERE conname = 'procurement_requests_status_check'
    SQL);

    // The purchasing lifecycle is unchanged: no `clarification_requested`, no
    // reschedule semantics leaked into it.
    expect($check?->def ?? '')->not->toContain('clarification_requested');
});
