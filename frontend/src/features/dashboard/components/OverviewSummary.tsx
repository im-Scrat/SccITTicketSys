import type { TicketOverview } from '@/features/analytics/types'
import { WidgetCard } from './WidgetCard'

/**
 * The overview in plain sentences, and how every figure is counted.
 *
 * The sentences come from fixed rules on the server over the same numbers the
 * charts show — **not AI** — and the label says so, so they are never mistaken
 * for an interpretation. Caveats (small numbers, partial records, duplicates
 * included) sit beneath, and the definitions behind a disclosure.
 */
export function OverviewSummary({ overview }: { overview: TicketOverview }) {
  const { summary } = overview.data
  const { meta } = overview

  return (
    <WidgetCard
      variant="section"
      title="Summary"
      description="Calculated from recorded tickets with fixed rules; nothing here is generated by AI."
    >
      <div className="flex flex-col gap-5">
        {summary.sentences.length > 0 && (
          <ul className="measure flex list-disc flex-col gap-2 pl-6 text-base text-ink marker:text-faint">
            {summary.sentences.map((sentence) => (
              <li key={sentence.key}>{sentence.text}</li>
            ))}
          </ul>
        )}
        {summary.caveats.length > 0 && (
          <ul aria-label="Caveats" className="measure flex flex-col gap-1.5 text-sm text-muted">
            {summary.caveats.map((caveat) => (
              <li key={caveat}>{caveat}</li>
            ))}
          </ul>
        )}
        <details className="text-sm">
          <summary className="w-fit cursor-pointer rounded-sm font-semibold text-primary-strong">
            How each figure is counted
          </summary>
          <dl className="measure mt-3 flex flex-col gap-3">
            {meta.definitions.map((definition) => (
              <div key={definition.term}>
                <dt className="font-semibold text-ink-strong">{definition.term}</dt>
                <dd className="mt-0.5 text-muted">{definition.text}</dd>
              </div>
            ))}
            <div>
              <dt className="font-semibold text-ink-strong">Time zone</dt>
              <dd className="mt-0.5 text-muted">
                Every date and period uses {meta.timezone_label}. {meta.as_of_label}.
              </dd>
            </div>
          </dl>
        </details>
      </div>
    </WidgetCard>
  )
}
