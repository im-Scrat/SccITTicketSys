/**
 * Client mirror of the WP-M predictive-maintenance review API
 * (`/api/admin/predictions`). Admin-only — see `RequirePredictions`.
 */

import type { Paginated } from '@/features/tickets/types'

export type PredictionStatusValue = 'pending' | 'confirmed' | 'dismissed' | 'expired'

export type PredictionRiskValue = 'low' | 'medium' | 'high'

/** Presentation tone comes from the API — the client never picks a status/risk hue. */
export type PredictionTone = 'neutral' | 'info' | 'success' | 'warning' | 'danger'

export interface PredictionStatusRef {
  value: PredictionStatusValue
  label: string
}

export interface PredictionRiskRef {
  value: PredictionRiskValue
  label: string
  tone: PredictionTone
}

export interface PredictionPcUnitRef {
  id: string
  label: string
  identifier: string
  asset_tag?: string | null
}

export interface PredictionLocationRef {
  room: string | null
  floor?: string | null
  building?: string | null
}

/** A prediction card, as the list surface shows it. */
export interface PredictionListItem {
  id: string
  pc_unit: PredictionPcUnitRef | null
  predicted_issue: string
  risk_level: PredictionRiskRef | null
  confidence: number | null
  status: PredictionStatusRef
  generated_at: string | null
}

/** One component type replaced across a PC's corrective repairs. */
export interface EvidenceComponentReplaced {
  component_type: string
  label: string
  count: number
}

/** A recurrence the deterministic detector found — never generated by the model. */
export interface EvidencePattern {
  kind: 'component' | 'fault_category' | 'repair_frequency'
  name: string
  detected_problem: string
  occurrence_count: number
  intervals_days: number[]
  average_days_between: number | null
  first_at: string
  last_at: string
  records: string[]
}

/** The observed facts and detected pattern(s) a prediction was generated from. */
export interface PredictionEvidence {
  observed: {
    completed_repairs?: number
    corrective_repairs?: number
    preventive_visits?: number
    first_completed_at?: string | null
    last_completed_at?: string | null
    components_replaced?: EvidenceComponentReplaced[]
  }
  patterns: EvidencePattern[]
  time_window: {
    days: number | null
    basis: string
  }
}

/** One predictive-maintenance finding, in full. */
export interface PredictionDetail {
  id: string
  pc_unit: PredictionPcUnitRef | null
  location: PredictionLocationRef | null
  predicted_issue: string
  risk_level: PredictionRiskRef | null
  /** Always null today: no calibrated failure model exists. Served honestly, not omitted. */
  probability: number | null
  confidence: number | null
  predicted_within_days: number | null
  explanation: string
  recommendation: string
  evidence: PredictionEvidence
  ai_model: { provider: string; model: string } | null
  failure_pattern: { id: number; name: string; occurrence_count: number } | null
  status: PredictionStatusRef
  can: { decide: boolean }
  generated_at: string | null
  created_at: string | null
}

export interface PredictionListEnvelope extends Paginated<PredictionListItem> {}

export interface PredictionDetailEnvelope {
  data: PredictionDetail
}

export interface PredictionListParams {
  status?: string
  risk_level?: string
  page?: number
  per_page?: number
}
